#!/bin/sh
# Export the real-time mascot from Blender, compress it (meshopt geometry, WebP texture) and embed
# it as a base64 module so the DOM bundle can load it without a file URL.
set -eu
HERE=$(cd "$(dirname "$0")" && pwd)
OUT="$HERE/../../src/dom/assets/mascot"
TMP=$(mktemp -d /tmp/zunos-glb.XXXXXX)
mkdir -p "$OUT"
blender -b --factory-startup -t 4 -P "$HERE/export_glb.py" -- --out "$TMP/raw.glb" > "$TMP/blender.log" 2>&1 \
  || { tail -40 "$TMP/blender.log"; exit 1; }
T="npx -y @gltf-transform/cli@4"
$T dedup "$TMP/raw.glb" "$TMP/a.glb"
$T prune "$TMP/a.glb" "$TMP/b.glb"
$T webp "$TMP/b.glb" "$TMP/c.glb" --quality 90
$T meshopt "$TMP/c.glb" "$OUT/zunos.glb" --level medium
python3 - "$OUT/zunos.glb" "$OUT/zunos-glb.ts" <<'EOF'
import base64, sys
data = base64.b64encode(open(sys.argv[1], "rb").read()).decode()
open(sys.argv[2], "w").write(
    "// Generated by apps/mac/assets/mascot/build_glb.sh from zunos.glb. Do not edit.\n"
    f"export const ZUNOS_GLB_BASE64 =\n  \"{data}\";\n"
)
EOF
ls -l "$OUT"
rm -rf "$TMP"
