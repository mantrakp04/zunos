import AppKit
import Carbon.HIToolbox

/// Puts text into whatever app has focus: through the pasteboard and a synthesized ⌘V, then gives the
/// user their clipboard back. Needs the Accessibility permission to post the keystroke.
enum Paster {
  /// Marks our temporary pasteboard contents so clipboard managers skip them (nspasteboard.org).
  private static let markers = ["org.nspasteboard.TransientType", "org.nspasteboard.AutoGeneratedType"].map { NSPasteboard.PasteboardType($0) }

  static func paste(_ text: String, restoreClipboard: Bool, completion: @escaping (Bool) -> Void) {
    let pb = NSPasteboard.general
    let saved = restoreClipboard ? snapshot(pb) : nil
    pb.clearContents()
    pb.setString(text, forType: .string)
    for m in markers { pb.setData(Data(), forType: m) }
    let ours = pb.changeCount

    // The hotkey's modifier may still be down: ⌥ or fn held during ⌘V turns it into another shortcut.
    waitForModifiersUp(deadline: Date().addingTimeInterval(0.6)) {
      guard Hotkey.trusted else { return completion(false) }
      postCommandV()
      guard let saved else { return completion(true) }
      // Give the target app time to read the pasteboard before restoring the user's clipboard.
      DispatchQueue.main.asyncAfter(deadline: .now() + 0.8) {
        if pb.changeCount == ours { restore(saved, to: pb) }
        completion(true)
      }
    }
  }

  private static func postCommandV() {
    let src = CGEventSource(stateID: .privateState)
    let v = CGKeyCode(kVK_ANSI_V)
    let down = CGEvent(keyboardEventSource: src, virtualKey: v, keyDown: true)
    let up = CGEvent(keyboardEventSource: src, virtualKey: v, keyDown: false)
    down?.flags = .maskCommand
    up?.flags = .maskCommand
    down?.post(tap: .cghidEventTap)
    up?.post(tap: .cghidEventTap)
  }

  private static func waitForModifiersUp(deadline: Date, then: @escaping () -> Void) {
    let held: CGEventFlags = [.maskAlternate, .maskCommand, .maskControl, .maskShift, .maskSecondaryFn]
    if CGEventSource.flagsState(.combinedSessionState).intersection(held).isEmpty || Date() > deadline { return then() }
    DispatchQueue.main.asyncAfter(deadline: .now() + 0.02) { waitForModifiersUp(deadline: deadline, then: then) }
  }

  private static func snapshot(_ pb: NSPasteboard) -> [[NSPasteboard.PasteboardType: Data]] {
    (pb.pasteboardItems ?? []).map { item in
      Dictionary(uniqueKeysWithValues: item.types.compactMap { t in item.data(forType: t).map { (t, $0) } })
    }
  }

  private static func restore(_ items: [[NSPasteboard.PasteboardType: Data]], to pb: NSPasteboard) {
    pb.clearContents()
    guard !items.isEmpty else { return }
    pb.writeObjects(items.map { types in
      let item = NSPasteboardItem()
      for (t, d) in types { item.setData(d, forType: t) }
      return item
    })
  }
}
