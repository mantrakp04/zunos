// Embeds drizzle-kit's SQL migrations into src/migrations.gen.ts so the same migrations run from the
// app (expo-sqlite, no fs access to .sql files) and from bun scripts (bun:sqlite).
import { readFileSync, writeFileSync } from "node:fs";

const dir = new URL("../migrations/", import.meta.url);
const journal = JSON.parse(readFileSync(new URL("meta/_journal.json", dir), "utf8"));
const migrations = journal.entries.map((e: { tag: string }) => ({
  tag: e.tag,
  sql: readFileSync(new URL(`${e.tag}.sql`, dir), "utf8"),
}));
writeFileSync(
  new URL("../src/migrations.gen.ts", import.meta.url),
  `// Generated by scripts/embed-migrations.ts. Do not edit.\nexport const migrations: { tag: string; sql: string }[] = ${JSON.stringify(migrations, null, 2)};\n`,
);
console.log(`embedded ${migrations.length} migration(s)`);
