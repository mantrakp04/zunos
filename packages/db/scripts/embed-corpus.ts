// Lists the reading corpus (corpus/<code>.json, not the .synth.json pools) in src/corpus.gen.ts so the app
// (Metro) and bun scripts load the same files. Each language's file is only parsed when it is first seeded.
// Run after a corpus file is added or changed: `bun run corpus` in packages/db.
import { readdirSync, readFileSync, writeFileSync } from "node:fs";

const dir = new URL("../corpus/", import.meta.url);
const files = readdirSync(dir).filter((f) => /^[a-z]{2,3}\.json$/.test(f)).sort();
const rows = files.map((f) => {
  const text = readFileSync(new URL(f, dir), "utf8");
  const data = JSON.parse(text) as { lang: string; starter: string[]; items: { id: string; roman: string[] | null }[] };
  const code = f.replace(/\.json$/, "");
  if (data.lang !== code) throw new Error(`${f}: lang is ${data.lang}`);
  const ids = new Set(data.items.map((i) => i.id));
  const missing = data.starter.filter((id) => !ids.has(id));
  if (missing.length) throw new Error(`${f}: starter ids not in items: ${missing.join(", ")}`);
  const version = new Bun.CryptoHasher("sha1").update(text).digest("hex").slice(0, 12);
  const roman = data.items.some((i) => i.roman);
  return `  ${JSON.stringify(code)}: { version: "${version}", roman: ${roman}, load: () => require("../corpus/${f}") },`;
});
writeFileSync(
  new URL("../src/corpus.gen.ts", import.meta.url),
  `// Generated by scripts/embed-corpus.ts. Do not edit.\nimport type { CorpusFile } from "./corpus";\n\n` +
    `/** The reading corpus per language: a content hash, whether it has English-letter lines, and the file. */\n` +
    `export const CORPUS: Record<string, { version: string; roman: boolean; load: () => CorpusFile }> = {\n${rows.join("\n")}\n};\n`,
);
console.log(`embedded the corpus of ${files.length} language(s)`);
